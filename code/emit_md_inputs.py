#!/usr/bin/env python3
"""
Regenerate the GROMACS/packmol run inputs for the adsorption screen.

The numeric run constants (COMMON, NPOLY, PROD_NS, BXY, POLYS, PFASS, SEEDS)
are read programmatically (via `ast`) from the archived MD driver
`code/batch_run.py`; the .mdp and packmol templates are transcribed from it,
which is the script that produced `data/raw_results.csv`. Running this script
therefore reproduces the exact `.mdp` and `packmol` inputs used for the
production runs, byte for byte.

What this script CANNOT regenerate, because the underlying structures are not
archived: the acpype/GAFF2 topologies (`*_GMX.itp`), the polymer and PFAS
`.pdb` structures, `index.ndx` (its atom ranges depend on those `.pdb` files),
and the umbrella-sampling / `gmx wham` inputs and outputs. Those must come from
the original compute node.

Usage:  python code/emit_md_inputs.py
Output: md_inputs/<POLYMER>_<PFAS>/{em,ions,npt,s<N>_prod,s<N>_re}.mdp, pack.inp
        md_inputs/docking/smina_1K7L.conf
        md_inputs/MANIFEST.md
"""
import ast, json, os, textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DRIVER = os.path.join(HERE, "batch_run.py")
DATA = os.path.join(ROOT, "data")
OUT = os.path.join(ROOT, "md_inputs")

src = open(DRIVER, encoding="utf-8").read()
tree = ast.parse(src)

def const(name):
    """Pull a module-level constant out of the driver without executing it."""
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name) and t.id == name:
                    return ast.literal_eval(node.value)
    raise KeyError(name)

COMMON  = const("COMMON")
NPOLY   = const("NPOLY")
PROD_NS = const("PROD_NS")
BXY     = const("BXY")
POLYS   = const("POLYS")
PFASS   = const("PFASS")
SEEDS   = const("SEEDS")

# --- the five .mdp templates, transcribed structurally from batch_run.py ---
EM = "integrator=steep\nnsteps=3000\nemtol=1000\nemstep=0.01\nnstlist=10\n" + COMMON.split("tcoupl")[0]
NPT = ("integrator=md\ndt=0.002\nnsteps=100000\nnstlist=20\n" + COMMON +
       "pcoupl=C-rescale\npcoupltype=isotropic\ntau-p=2.0\nref-p=1.0\n"
       "compressibility=4.5e-5\ngen-vel=yes\ngen-temp=300\n")
NSTEPS = int(PROD_NS * 1000 / 0.002)
def prod_mdp(seed):
    return (f"integrator=md\ndt=0.002\nnsteps={NSTEPS}\nnstlist=40\nnstenergy=5000\n"
            f"nstxout-compressed=5000\n" + COMMON +
            "pcoupl=C-rescale\npcoupltype=isotropic\ntau-p=2.0\nref-p=1.0\ncompressibility=4.5e-5\n"
            f"gen-vel=yes\ngen-temp=300\ngen-seed={seed*1000+7}\n")
RERUN = f"integrator=md\ndt=0.002\nnsteps=0\nnstlist=40\n" + COMMON + "energygrps=POL PFA\n"
def pack_inp(poly, pfas, wd):
    return (f"tolerance 2.0\nfiletype pdb\noutput {wd}/dry.pdb\n"
            f"structure polymers/{poly}.pdb\n  number {NPOLY}\n"
            f"  inside box 2. 2. 2. {BXY-2} {BXY-2} 28.\nend structure\n"
            f"structure pfas/{pfas}.pdb\n  number 1\n"
            f"  inside box 8. 8. 29. {BXY-8} {BXY-8} 40.\nend structure\n")

# polymers that actually produced trajectories (PP was planned but never completed)
import csv
ran = sorted({(r["polymer"], r["pfas"]) for r in csv.DictReader(open(os.path.join(DATA, "raw_results.csv")))})

n = 0
for poly, pfas in ran:
    d = os.path.join(OUT, f"{poly}_{pfas}"); os.makedirs(d, exist_ok=True)
    wd = f"systems/{poly}_{pfas}"
    open(os.path.join(d, "em.mdp"), "w").write(EM)
    open(os.path.join(d, "ions.mdp"), "w").write(EM)      # driver writes the same content to both
    open(os.path.join(d, "npt.mdp"), "w").write(NPT)
    open(os.path.join(d, "pack.inp"), "w").write(pack_inp(poly, pfas, wd))
    for s in SEEDS:
        open(os.path.join(d, f"s{s}_prod.mdp"), "w").write(prod_mdp(s))
        open(os.path.join(d, f"s{s}_re.mdp"), "w").write(RERUN)
    n += 1

# --- docking configuration, transcribed from the recorded run metadata ---
dock = json.load(open(os.path.join(DATA, "rq3_docking.json")))
dd = os.path.join(OUT, "docking"); os.makedirs(dd, exist_ok=True)
cx, cy, cz = dock["box_center"]; sx, sy, sz = dock["box_size"]
open(os.path.join(dd, "smina_1K7L.conf"), "w").write(
    f"# reconstructed from data/rq3_docking.json (engine: {dock['engine']})\n"
    f"# receptor: {dock['receptor']}\n"
    f"center_x = {cx}\ncenter_y = {cy}\ncenter_z = {cz}\n"
    f"size_x = {sx}\nsize_y = {sy}\nsize_z = {sz}\n"
    f"exhaustiveness = {dock['exhaustiveness']}\nseed = {dock['seed']}\n")

open(os.path.join(OUT, "MANIFEST.md"), "w").write(textwrap.dedent(f"""\
    # md_inputs — provenance

    Generated by `code/emit_md_inputs.py`. Nothing here is hand-written.

    ## Regenerated from `code/batch_run.py` (the driver that produced `data/raw_results.csv`)

    - `<POLYMER>_<PFAS>/em.mdp`, `ions.mdp`, `npt.mdp`, `s<N>_prod.mdp`, `s<N>_re.mdp`
    - `<POLYMER>_<PFAS>/pack.inp`
    - {n} systems x {len(SEEDS)} seeds; production {PROD_NS} ns ({NSTEPS} steps at 2 fs)
    - slab: {NPOLY} oligomer chains per polymer; packmol box {BXY} x {BXY} A;
      `gmx editconf -box 4.0 4.0 8.0` (nm)
    - interaction energy: single-point `-rerun` with `energygrps=POL PFA`,
      averaged from 2 ns onward (`gmx energy -b 2000`)

    ## Transcribed from recorded run metadata

    - `docking/smina_1K7L.conf` <- `data/rq3_docking.json`

    ## NOT reproducible here — required from the original compute node

    - acpype/GAFF2 topologies (`*_GMX.itp`) and the polymer / PFAS `.pdb` structures
    - `index.ndx` (atom ranges depend on those `.pdb` files)
    - umbrella-sampling window definitions and `gmx wham` output
      (`profile.xvg`, `bsResult.xvg`) for PVDF+PFOA and ECTFE+PFOA
    """))
print(f"wrote {n} system directories + docking config + MANIFEST under {OUT}")
